// Writes compositions/captions.html.
// With assets/transcript.json (from `npx hyperframes transcribe assets/vo.wav --model small.en`)
// the groups use real word timings; without it, each beat's text in vo-script.json is spread
// evenly across its window, weighted by word length.
import fs from "node:fs";
import path from "node:path";

const dir = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, "$1")), "..");
const transcriptPath = path.join(dir, "assets", "transcript.json");
const MAX_WORDS = 5;
const PAUSE = 0.15;

function estimatedWords() {
  const beats = JSON.parse(fs.readFileSync(path.join(dir, "vo-script.json"), "utf8"));
  const words = [];
  for (const b of beats) {
    const tokens = b.text.split(/\s+/).filter(Boolean);
    const weight = (t) => t.length + 2 + (/[.,:;!?]$/.test(t) ? 4 : 0);
    const total = tokens.reduce((s, t) => s + weight(t), 0);
    let t = b.start;
    const span = b.end - b.start;
    for (const tok of tokens) {
      const d = (weight(tok) / total) * span;
      words.push({ text: tok, start: t, end: t + d * 0.85 });
      t += d;
    }
  }
  return words;
}

// Whisper's spellings → the script's.
const FIX = {
  Lucia: "Lucía",
  "Lucia's": "Lucía's",
  "Lucia.": "Lucía.",
  "Lucia,": "Lucía,",
  Teotitran: "Teotitlán",
  counter: "Counter",
  renderer: "Render",
  "co-pilot.": "copilot.",
  "110.": "$110.",
  Oaxaca: "Oaxaca,",
  "disbursement": "disbursement,",
};
const fixWord = (t, prev) =>
  t === "paid" && prev === "onboarding," ? "payee" : t === "and" && prev === "policy" ? "in" : FIX[t] ?? t;

function transcriptWords() {
  const raw = JSON.parse(fs.readFileSync(transcriptPath, "utf8"));
  const list = Array.isArray(raw) ? raw : raw.words ?? raw.segments?.flatMap((s) => s.words) ?? [];
  return list
    .map((w) => ({ text: String(w.text ?? w.word).trim(), start: w.start, end: w.end }))
    .filter((w) => w.text && !/^[♪�]+$/.test(w.text))
    .map((w, i, a) => ({ ...w, text: fixWord(w.text, a[i - 1]?.text) }));
}

function group(words) {
  const groups = [];
  let cur = [];
  for (let i = 0; i < words.length; i++) {
    const w = words[i];
    cur.push(w);
    const next = words[i + 1];
    const sentenceEnd = /[.!?:]$/.test(w.text);
    const pause = next && next.start - w.end >= PAUSE;
    if (!next || sentenceEnd || pause || cur.length >= MAX_WORDS || (/,$/.test(w.text) && cur.length >= 3)) {
      groups.push(cur);
      cur = [];
    }
  }
  return groups.map((g, i) => {
    const next = groups[i + 1];
    const start = Math.max(0.1, g[0].start - 0.05);
    let end = g[g.length - 1].end + 0.25;
    if (next) end = Math.min(end, next[0].start - 0.05);
    return { text: g.map((w) => w.text).join(" "), start: +start.toFixed(3), end: +end.toFixed(3) };
  });
}

const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const usingTranscript = fs.existsSync(transcriptPath);
const groups = group(usingTranscript ? transcriptWords() : estimatedWords());

const html = `<template>
  <!-- Generated by tools/captions.mjs from ${usingTranscript ? "assets/transcript.json" : "vo-script.json (estimated timing)"}. Re-run it instead of editing. -->
  <style>
    @font-face {
      font-family: "Geist";
      src: url("assets/fonts/geist-latin.woff2") format("woff2");
      font-weight: 100 900;
    }
    #root {
      position: absolute;
      inset: 0;
      pointer-events: none;
    }
    .cap {
      position: absolute;
      left: 0;
      right: 0;
      bottom: 96px;
      text-align: center;
      overflow: visible;
      opacity: 0;
    }
    .cap span {
      display: inline-block;
      max-width: 1500px;
      padding: 10px 26px 12px;
      border-radius: 14px;
      background: rgba(37, 26, 21, 0.82);
      color: #fcfaf6;
      font-family: "Geist", sans-serif;
      font-size: 46px;
      font-weight: 500;
      line-height: 1.2;
    }
  </style>
  <div id="root" data-composition-id="captions" data-width="1920" data-height="1080">
${groups.map((g, i) => `    <div class="cap" id="cap-${i}"><span>${esc(g.text)}</span></div>`).join("\n")}
  </div>
  <script>
    const tl = gsap.timeline({ paused: true });
    const groups = ${JSON.stringify(groups.map((g) => [g.start, g.end]))};
    groups.forEach(([start, end], i) => {
      const el = "#cap-" + i;
      tl.set(el, { visibility: "visible" }, start);
      tl.fromTo(el, { opacity: 0 }, { opacity: 1, duration: 0.1, ease: "power2.out", immediateRender: false }, start);
      tl.to(el, { opacity: 0, duration: 0.1, ease: "power2.in" }, end - 0.1);
      tl.set(el, { opacity: 0, visibility: "hidden" }, end);
    });
    window.__timelines["captions"] = tl;
  </script>
</template>
`;

fs.writeFileSync(path.join(dir, "compositions", "captions.html"), html);
console.log(`${groups.length} caption groups from ${usingTranscript ? "transcript" : "vo-script.json (estimated)"}`);
