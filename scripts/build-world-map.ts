// Bakes the world map the maker app draws order arcs on: public/world.svg (land, no Antarctica) and
// lib/geo/world-points.ts (each ISO country's center in the same coordinates). Run again only to change
// the projection or size; the app itself has no map dependency.
// Usage: pnpm map:build
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoEqualEarth, geoPath } from "d3-geo";
import { merge } from "topojson-client";
import type { GeometryCollection, MultiPolygon, Polygon, Topology } from "topojson-specification";

const require = createRequire(import.meta.url);
const topo = require("world-atlas/countries-110m.json") as Topology<{ countries: GeometryCollection }>;
const countries = require("world-countries") as { cca2: string; latlng: [number, number] }[];

const WIDTH = 1000;
const ANTARCTICA = "010";

// countries-110m holds only (Multi)Polygons.
const shapes = topo.objects.countries.geometries as (Polygon | MultiPolygon)[];
const land = merge(topo, shapes.filter((g) => g.id !== ANTARCTICA));
const projection = geoEqualEarth().fitWidth(WIDTH, land);
const path = geoPath(projection).digits(1);
const height = Math.ceil(path.bounds(land)[1][1]);

writeFileSync(
  "public/world.svg",
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${WIDTH} ${height}"><path fill="#d9d0c1" d="${path(land)}"/></svg>\n`,
);

// world-countries' latlng is a hand-picked center: better than a centroid for countries with far-off
// territories (France's would land in the Atlantic).
const points = Object.fromEntries(
  countries
    .map(({ cca2, latlng: [lat, lng] }) => [cca2, projection([lng, lat])] as const)
    .filter((e): e is readonly [string, [number, number]] => e[1] !== null)
    .map(([cca2, [x, y]]) => [cca2, [Math.round(x), Math.round(y)]])
    .sort(([a], [b]) => String(a).localeCompare(String(b))),
);

writeFileSync(
  "lib/geo/world-points.ts",
  `// Generated by scripts/build-world-map.ts. Do not edit.\n\n` +
    `export const MAP_WIDTH = ${WIDTH};\nexport const MAP_HEIGHT = ${height};\n\n` +
    `export const COUNTRY_POINTS: Record<string, [number, number]> = ${JSON.stringify(points)};\n`,
);

console.log(`world.svg ${WIDTH}×${height}, ${Object.keys(points).length} country points`);
